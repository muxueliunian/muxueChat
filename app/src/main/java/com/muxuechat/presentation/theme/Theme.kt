@Composable
fun MuxueChatTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    displayScale: DisplayScale = DisplayScale.DEFAULT,
    content: @Composable () -> Unit,
) {
    val typography = remember(displayScale) {
        MuxueChatTypography.scaledBy(displayScale.multiplier)
    }

    // 状态栏/导航栏图标的明暗必须跟着主题走。
    // MainActivity 只在 onCreate 调了一次无参 enableEdgeToEdge()，而 AndroidManifest 的
    // configChanges 里带了 uiMode——切换深浅色时 Activity 不重建，onCreate 不会再执行，
    // 于是图标颜色永远停在首次启动时的判定：浅色模式下白底白字，时间和电量完全看不见。
    // 这里跟随 darkTheme 重新设置，才能和 Compose 侧的 isSystemInDarkTheme() 保持一致。
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !darkTheme
                isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = typography,
        shapes = androidx.compose.material3.Shapes(
            extraSmall = Corner.Control, small = Corner.Control, medium = Corner.Container,
            large = Corner.Container, extraLarge = androidx.compose.foundation.shape.RoundedCornerShape(24.dp),
        ),
        content = content,
    )
}
